export function formatDisplayDate(dateValue, locale = 'en') {
  if (!dateValue) {
    return locale === 'bg' ? 'Неизвестна дата' : 'Unknown Date';
  }

  const date = new Date(dateValue);
  if (Number.isNaN(date.getTime())) {
    return locale === 'bg' ? 'Неизвестна дата' : 'Unknown Date';
  }

  return date
    .toLocaleString(locale === 'bg' ? 'bg-BG' : 'en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
      hourCycle: 'h23',
    })
    .replace(' at ', ' - ');
}
